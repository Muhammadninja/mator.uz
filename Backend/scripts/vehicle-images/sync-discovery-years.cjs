#!/usr/bin/env node
// Reuse the existing catalog's explicit start-year samples, never its open-ended
// 2099 UI bounds or a guessed production/generation range.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { createHash } = require('node:crypto');
const ts = require('typescript');

const args = process.argv.slice(2);
const sourceIndex = args.indexOf('--source-dir');
if (sourceIndex < 0 || !args[sourceIndex + 1]) {
  throw new Error(
    'Usage: node scripts/vehicle-images/sync-discovery-years.cjs --source-dir <MatorUI checkout> [--check]',
  );
}
const sourceFile = path.join(
  args[sourceIndex + 1],
  'services/uz-vehicle-catalog.ts',
);
const source = fs.readFileSync(sourceFile, 'utf8');
const compiled = ts.transpileModule(source, {
  compilerOptions: {
    module: ts.ModuleKind.CommonJS,
    target: ts.ScriptTarget.ES2023,
  },
}).outputText;
const exportsObject = {};
vm.runInNewContext(compiled, { exports: exportsObject });
const rows = exportsObject.UZ_GENERATIONS.map((generation) => {
  const model = exportsObject.UZ_MODELS.find(
    (item) => item.id === generation.modelId,
  );
  const year = generation.yearRange[0];
  if (!model || !Number.isInteger(year) || year < 1886 || year > 2200) {
    throw new Error('Invalid source catalog generation start-year sample');
  }
  return {
    makeId: model.brandId,
    modelId: model.id,
    sourceGenerationId: generation.id,
    year,
  };
});
const hash = createHash('sha256').update(source).digest('hex');
const output =
  `// Generated by scripts/vehicle-images/sync-discovery-years.cjs; do not edit.\n` +
  `// Source: MatorUI-/services/uz-vehicle-catalog.ts (SHA-256 ${hash}).\n` +
  `// Samples only: these are NOT production ranges or verified visual generations.\n` +
  `export const DISCOVERY_YEAR_SOURCE_SHA256 = '${hash}';\n` +
  `export const DISCOVERY_YEAR_SAMPLES = ${JSON.stringify(rows, null, 2)} as const;\n`;
const destination = path.resolve(
  __dirname,
  '../../src/garage/vehicle-images/vehicle-image.discovery-years.data.ts',
);
if (args.includes('--check')) {
  if (fs.readFileSync(destination, 'utf8') !== output) {
    throw new Error(
      'Discovery year metadata drifted from the canonical MatorUI catalog; regenerate and review.',
    );
  }
  console.log('Discovery year metadata matches the canonical source catalog.');
} else {
  fs.writeFileSync(destination, output);
  console.log(
    `Generated ${rows.length} explicit start-year samples; no year ranges changed.`,
  );
}
